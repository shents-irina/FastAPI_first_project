from utils.db_manager import DBManager


class BaseService:
    """Базовый класс сервисов.

    Хранит менеджер работы с базой данных, через который сервисы обращаются к репозиториям.
    Менеджер должен быть уже открыт через ``async with`` к моменту вызова методов сервиса.

    Соглашение для наследников: каждый метод, изменяющий данные, сам вызывает ``db.commit()`` после успешной операции.
    Вызывающему коду фиксировать транзакцию не нужно.
    Методы, которые изменяют данные без ``commit``, должны явно указывать это в своём докстринге.
    """

    db: DBManager

    def __init__(self, db: DBManager) -> None:
        self.db = db
